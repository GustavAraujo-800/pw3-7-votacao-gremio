CREATE DATABASE votacao_gremio;
USE votacao_gremio;

CREATE TABLE ELEITOR_S(
Id_E BIGINT IDENTITY(1,1) NOT NULL,
NOME_E VARCHAR(255) NOT NULL,
GMAIL VARCHAR(255) NULL ,
SENHA VARCHAR(255) NULL,
VOTO INT NULL,
);

CREATE TABLE CANDIDATO_S(
ID_C BIGINT IDENTITY(1,1) NOT NULL,
NOME_C VARCHAR(255) NOT NULL,
CATEGORIA VARCHAR(255) NOT NULL,
QUANTIDADE_DE_VOTOS INT NULL,
ELEITO VARCHAR(255) NOT NULL,
);